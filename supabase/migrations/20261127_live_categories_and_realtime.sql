create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  name text unique not null,
  slug text unique not null,
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

insert into public.categories (name, slug, sort_order) values
  ('Acid Wash', 'acid-wash', 1), ('Hoodies', 'hoodies', 2), ('Sweatshirts', 'sweatshirts', 3), ('Bottoms', 'bottoms', 4)
on conflict (name) do nothing;

alter table public.categories enable row level security;
drop policy if exists "Public reads categories" on public.categories;
drop policy if exists "Admin manages categories" on public.categories;
create policy "Public reads categories" on public.categories for select using (true);
create policy "Admin manages categories" on public.categories for all using (public.is_admin()) with check (public.is_admin());

