create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text,
  email text,
  role text not null default 'customer' check (role in ('customer', 'admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.products (
  id bigint primary key,
  name text not null,
  category text not null,
  price integer not null check (price >= 0),
  compare_at_price integer,
  image_url text not null,
  badge text,
  description text not null default '',
  sizes text[] not null default '{}',
  colours text[] not null default '{}',
  stock integer not null default 0 check (stock >= 0),
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  order_number text unique not null,
  customer_id uuid not null references public.profiles(id),
  total integer not null check (total >= 0),
  payment_method text not null check (payment_method in ('razorpay', 'cod')),
  payment_status text not null default 'pending',
  fulfilment_status text not null default 'new' check (fulfilment_status in ('new', 'processing', 'shipped', 'delivered', 'cancelled')),
  shipping_address jsonb not null default '{}'::jsonb,
  razorpay_order_id text,
  shiprocket_shipment_id text,
  created_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders(id) on delete cascade,
  product_id bigint references public.products(id),
  product_name text not null,
  size text,
  quantity integer not null check (quantity > 0),
  unit_price integer not null check (unit_price >= 0)
);

create table if not exists public.store_settings (
  id smallint primary key default 1 check (id = 1),
  brand_name text not null default 'FXX',
  logo_url text not null default '',
  accent text not null default '#e66735',
  updated_at timestamptz not null default now()
);
insert into public.store_settings (id, brand_name) values (1, 'FXX') on conflict (id) do nothing;

-- Creates a profile automatically after an authenticated customer signs up.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  insert into public.profiles (id, full_name, email)
  values (new.id, new.raw_user_meta_data ->> 'full_name', new.email)
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

create or replace function public.is_admin()
returns boolean
language sql stable security definer set search_path = public
as $$ select exists(select 1 from public.profiles where id = auth.uid() and role = 'admin'); $$;

alter table public.profiles enable row level security;
alter table public.products enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;
alter table public.store_settings enable row level security;

-- Profiles: users can only see/update their own profile; admin can see all.
create policy "Users read own profile" on public.profiles for select using (auth.uid() = id or public.is_admin());
create policy "Users update own profile" on public.profiles for update using (auth.uid() = id) with check (auth.uid() = id and role = (select role from public.profiles where id = auth.uid()));

-- Products: public read-only catalogue. Only admin can create/change products or stock.
create policy "Public reads active products" on public.products for select using (is_active = true or public.is_admin());
create policy "Admin creates products" on public.products for insert with check (public.is_admin());
create policy "Admin updates products" on public.products for update using (public.is_admin()) with check (public.is_admin());
create policy "Admin deletes products" on public.products for delete using (public.is_admin());

-- Orders: signed-in customers can create and read only their own orders. Admin handles all orders.
create policy "Customers read own orders" on public.orders for select using (auth.uid() = customer_id or public.is_admin());
create policy "Customers create own orders" on public.orders for insert with check (auth.uid() = customer_id);
create policy "Admin updates orders" on public.orders for update using (public.is_admin()) with check (public.is_admin());
create policy "Customers read own order items" on public.order_items for select using (exists(select 1 from public.orders where orders.id = order_items.order_id and (orders.customer_id = auth.uid() or public.is_admin())));
create policy "Customers create own order items" on public.order_items for insert with check (exists(select 1 from public.orders where orders.id = order_items.order_id and orders.customer_id = auth.uid()));
create policy "Admin manages order items" on public.order_items for all using (public.is_admin()) with check (public.is_admin());

create policy "Public reads store settings" on public.store_settings for select using (true);
create policy "Admin changes store settings" on public.store_settings for all using (public.is_admin()) with check (public.is_admin());

